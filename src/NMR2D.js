// 2D NMR helpers: build a 2D nmrML document, and predict a 1H-13C HSQC
// spectrum from assigned 1D 1H and 13C spectra.
//
// The nmrML layout follows the "2D NMR Data in nmrML" file specification:
// three uncompressed base64 Float64 arrays (F2 axis, F1 axis, row-major
// intensity grid) in <spectrumMultiD>, and optionally one <atomAssignment>
// with the structure and cross peaks as consecutive pairs of multiplets.

// Default predicted-HSQC grid and peak widths
const HSQC_DEFAULTS = {
    points_1h: 1024,      // direct dimension (F2) points
    points_13c: 512,      // indirect dimension (F1) points
    width_1h: 0.02,       // Gaussian standard deviation, ppm
    width_13c: 0.5,       // Gaussian standard deviation, ppm
};

// ---------------------------------------------------------------------------
// Encoding
// ---------------------------------------------------------------------------

// Base64 of little-endian 64-bit floats
export function encode_float64_base64(values) {
    const bytes = new Uint8Array(values.length * 8);
    const view = new DataView(bytes.buffer);
    for (let i = 0; i < values.length; i++) view.setFloat64(i * 8, values[i], true);
    let binary = '';
    const chunk = 0x8000;
    for (let i = 0; i < bytes.length; i += chunk) {
        binary += String.fromCharCode.apply(null, bytes.subarray(i, i + chunk));
    }
    return btoa(binary);
}

function escape_xml(text) {
    return String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

// ---------------------------------------------------------------------------
// nmrML writer
// ---------------------------------------------------------------------------

/**
 * Build a 2D nmrML document.
 *
 * @param {Object} spectrum
 *   x, y, z      F2 axis values, F1 axis values (ppm) and the row-major intensity
 *                grid (one row per y value); z.length must equal x.length * y.length
 *   id           spectrum id (default "2D-spectrum")
 *   name         compound or spectrum name
 *   experiment   e.g. "1H-13C HSQC" or "1H-1H COSY" (written as a comment)
 *   assignment   optional { atoms: [{id, element, x, y, z}], bonds: [{a1, a2, order}],
 *                cross_peaks: [{ x: {center, atom_refs}, y: {center, atom_refs} }] }
 *                with atom_refs such as ["H13", "H14"] and ["C1"]
 * @return {String} nmrML XML
 */
export function build_2d_nmrml(spectrum) {
    const { x, y, z } = spectrum;
    if (!x || !y || !z || z.length !== x.length * y.length) {
        throw new Error('2D nmrML: z length must equal x length * y length');
    }
    const id = spectrum.id || '2D-spectrum';
    const lines = [];
    lines.push('<?xml version="1.0" encoding="UTF-8"?>');
    lines.push('<nmrML xmlns="http://nmrml.org/schema" version="1.0.rc1">');
    lines.push('  <!-- Generated by JSpectraViewer' + (spectrum.experiment ? ': ' + escape_xml(spectrum.experiment) : '') + ' -->');
    lines.push('  <spectrumList>');
    lines.push(`    <spectrumMultiD id="${escape_xml(id)}" numberOfDataPoints="${z.length}">`);
    lines.push(`      <spectrumDataArray2dIntensities compressed="false" byteFormat="Float64">${encode_float64_base64(z)}</spectrumDataArray2dIntensities>`);
    lines.push(`      <spectrumDataArray2dDirectDimensionF2 compressed="false" byteFormat="Float64">${encode_float64_base64(x)}</spectrumDataArray2dDirectDimensionF2>`);
    lines.push(`      <spectrumDataArray2dIndirectDimensionF1 compressed="false" byteFormat="Float64">${encode_float64_base64(y)}</spectrumDataArray2dIndirectDimensionF1>`);
    lines.push('    </spectrumMultiD>');
    lines.push('  </spectrumList>');

    const assignment = spectrum.assignment;
    if (assignment && assignment.cross_peaks && assignment.cross_peaks.length > 0) {
        lines.push('  <spectrumAnnotationList>');
        lines.push(`    <atomAssignment spectrumRef="${escape_xml(id)}">`);
        lines.push('      <chemicalCompound>');
        lines.push(`        <identifierList><identifier name="${escape_xml(spectrum.name || 'Compound')}"/></identifierList>`);
        if (assignment.atoms && assignment.atoms.length > 0) {
            lines.push('        <structure>');
            lines.push('          <atomList>');
            assignment.atoms.forEach((a) => {
                lines.push(`            <atom id="${escape_xml(a.id)}" elementType="${escape_xml(a.element)}" x="${a.x}" y="${a.y}" z="${a.z}"/>`);
            });
            lines.push('          </atomList>');
            lines.push('          <bondList>');
            (assignment.bonds || []).forEach((b) => {
                lines.push(`            <bond atomRefs="${escape_xml(b.a1)} ${escape_xml(b.a2)}" order="${b.order || 1}"/>`);
            });
            lines.push('          </bondList>');
            lines.push('        </structure>');
        }
        lines.push('      </chemicalCompound>');
        lines.push('      <atomAssignmentList>');
        assignment.cross_peaks.forEach((cp) => {
            [cp.x, cp.y].forEach((signal) => {
                lines.push(`        <multiplet center="${signal.center}"><atoms atomRefs="${escape_xml(signal.atom_refs.join(' '))}"/></multiplet>`);
            });
        });
        lines.push('      </atomAssignmentList>');
        lines.push('    </atomAssignment>');
        lines.push('  </spectrumAnnotationList>');
    }
    lines.push('</nmrML>');
    return lines.join('\n') + '\n';
}

// ---------------------------------------------------------------------------
// Predicted HSQC from assigned 1D spectra
// ---------------------------------------------------------------------------

// Atoms and bonds from DataParser structure data (fast-xml-parser output,
// attributes prefixed "@_"), keyed by the numeric part of each atom id
function read_structure(assignment_data) {
    const structure = assignment_data && assignment_data.structure_data && assignment_data.structure_data.structure;
    if (!structure) return null;
    const as_array = (v) => (Array.isArray(v) ? v : (v ? [v] : []));
    const atoms = {};
    as_array(structure.atomList && structure.atomList.atom).forEach((a) => {
        const number = String(a['@_id']).replace(/\D/g, '');
        atoms[number] = {
            id: number, element: a['@_elementType'],
            x: parseFloat(a['@_x']) || 0, y: parseFloat(a['@_y']) || 0, z: parseFloat(a['@_z']) || 0,
        };
    });
    const bonds = as_array(structure.bondList && structure.bondList.bond).map((b) => {
        const [a1, a2] = String(b['@_atomRefs']).trim().split(/\s+/).map((r) => r.replace(/\D/g, ''));
        return { a1, a2, order: parseInt(b['@_order'], 10) || 1 };
    });
    return { atoms, bonds };
}

// Chemical shift of a 1D cluster: the mean of its peak centers
function cluster_center(cluster) {
    const peaks = cluster.peaks || [];
    if (peaks.length === 0) return NaN;
    return peaks.reduce((sum, p) => sum + p.center, 0) / peaks.length;
}

function same_structure(a, b) {
    const ids_a = Object.keys(a.atoms).sort();
    const ids_b = Object.keys(b.atoms).sort();
    return ids_a.length === ids_b.length &&
        ids_a.every((id, i) => id === ids_b[i] && a.atoms[id].element === b.atoms[id].element);
}

/**
 * Predict a 1H-13C HSQC spectrum from assigned 1D 1H and 13C spectra of the same
 * compound (DataParser "fileParsed" event.detail objects with assignmentData).
 * Each assigned carbon with directly bonded hydrogens gives one cross peak at
 * (1H shift of those hydrogens, 13C shift of the carbon), drawn as a 2D Gaussian
 * with height proportional to the number of hydrogens. Quaternary carbons give
 * no cross peak.
 *
 * @param {Object} proton  parsed 1D 1H spectrum (x, assignmentData)
 * @param {Object} carbon  parsed 1D 13C spectrum (x, assignmentData)
 * @param {Object} options grid size and peak widths (see HSQC_DEFAULTS)
 * @return {Object} { x, y, z, name, experiment, assignment, cross_peaks } ready for build_2d_nmrml
 */
export function predict_hsqc(proton, carbon, options = {}) {
    const opts = Object.assign({}, HSQC_DEFAULTS, options);
    const h_data = proton && proton.assignmentData;
    const c_data = carbon && carbon.assignmentData;
    if (!h_data || !c_data) {
        throw new Error('Predicted HSQC needs assigned 1D 1H and 13C spectra (nmrML with peak assignments).');
    }
    const structure = read_structure(c_data) || read_structure(h_data);
    if (!structure) throw new Error('Predicted HSQC needs a molecular structure in the 1D nmrML files.');
    const h_structure = read_structure(h_data);
    if (h_structure && !same_structure(structure, h_structure)) {
        throw new Error('The 1H and 13C files describe different structures (atom numbering differs); they must be for the same compound with the same atom numbering.');
    }

    // Hydrogens bonded to each carbon
    const bonded_hydrogens = {};
    structure.bonds.forEach(({ a1, a2 }) => {
        [[a1, a2], [a2, a1]].forEach(([heavy, h]) => {
            const heavy_atom = structure.atoms[heavy];
            const h_atom = structure.atoms[h];
            if (heavy_atom && h_atom && heavy_atom.element === 'C' && h_atom.element === 'H') {
                (bonded_hydrogens[heavy] = bonded_hydrogens[heavy] || []).push(h);
            }
        });
    });

    // 1H clusters, with the atoms they are assigned to
    const h_clusters = (h_data.clusters || []).map((c) => ({
        center: cluster_center(c), atom_refs: (c.meta && c.meta.atom_refs) || [],
    })).filter((c) => !isNaN(c.center));

    const cross_peaks = [];
    (c_data.clusters || []).forEach((c) => {
        const c_center = cluster_center(c);
        if (isNaN(c_center)) return;
        ((c.meta && c.meta.atom_refs) || []).forEach((carbon_id) => {
            if (!structure.atoms[carbon_id] || structure.atoms[carbon_id].element !== 'C') return;
            const hydrogens = bonded_hydrogens[carbon_id] || [];
            if (hydrogens.length === 0) return;    // quaternary carbon: no HSQC cross peak
            // 1H clusters assigned to these hydrogens (or to the carbon itself)
            h_clusters.forEach((h) => {
                const matched = hydrogens.filter((id) => h.atom_refs.includes(id));
                if (matched.length === 0 && !h.atom_refs.includes(carbon_id)) return;
                const h_atoms = matched.length > 0 ? matched : hydrogens;
                cross_peaks.push({
                    x: { center: +h.center.toFixed(4), atom_refs: h_atoms.map((id) => 'H' + id) },
                    y: { center: +c_center.toFixed(3), atom_refs: ['C' + carbon_id] },
                    intensity: h_atoms.length,
                });
            });
        });
    });
    if (cross_peaks.length === 0) {
        throw new Error('No cross peaks found: no assigned carbon has bonded hydrogens with an assigned 1H signal.');
    }

    // Axes: the 1D spectra's ranges, high to low ppm (the NMR convention), widened
    // where needed so every cross peak (plus a margin) is on the grid
    const axis = (values, centers, margin, points, fallback) => {
        let lo = Infinity;
        let hi = -Infinity;
        (values && values.length ? values : fallback).forEach((v) => {
            if (v < lo) lo = v;
            if (v > hi) hi = v;
        });
        centers.forEach((c) => {
            lo = Math.min(lo, c - margin);
            hi = Math.max(hi, c + margin);
        });
        const step = (hi - lo) / (points - 1);
        return Array.from({ length: points }, (_, i) => hi - i * step);
    };
    const x = axis(proton.x, cross_peaks.map((cp) => cp.x.center), 0.5, opts.points_1h, [-0.5, 12]);
    const y = axis(carbon.x, cross_peaks.map((cp) => cp.y.center), 10, opts.points_13c, [-5, 220]);

    // Gaussian cross peaks; widths at least 1.5 grid points so every peak is resolved
    const spacing_x = Math.abs(x[1] - x[0]);
    const spacing_y = Math.abs(y[1] - y[0]);
    const sx = Math.max(opts.width_1h, 1.5 * spacing_x);
    const sy = Math.max(opts.width_13c, 1.5 * spacing_y);
    const z = new Array(x.length * y.length).fill(0);
    cross_peaks.forEach((cp) => {
        const cx = cp.x.center;
        const cy = cp.y.center;
        // Only grid points within 4 standard deviations contribute
        for (let row = 0; row < y.length; row++) {
            const dy = (y[row] - cy) / sy;
            if (Math.abs(dy) > 4) continue;
            for (let col = 0; col < x.length; col++) {
                const dx = (x[col] - cx) / sx;
                if (Math.abs(dx) > 4) continue;
                z[row * x.length + col] += cp.intensity * Math.exp(-0.5 * (dx * dx + dy * dy));
            }
        }
    });

    const atoms = Object.values(structure.atoms);
    return {
        x, y, z,
        id: '2D-1H-13C-HSQC-predicted',
        name: c_data.name || h_data.name || 'Compound',
        experiment: 'predicted 1H-13C HSQC',
        cross_peaks,
        assignment: {
            atoms,
            bonds: structure.bonds,
            cross_peaks: cross_peaks.map(({ x, y }) => ({ x, y })),
        },
    };
}
